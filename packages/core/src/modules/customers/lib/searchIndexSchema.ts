/**
 * Read-only counts of the plaintext-equivalent copies (what the purge would
 * remove). Used by the script's dry run. Each statement returns one `n`.
 */
export function searchIndexLeakCountSql(): Array<{ label: string; sql: string; requires: string }> {
  const types = encryptedEntityTypes().map(q).join(', ')
  const pairs = encryptedFieldPairs().map(([t, f]) => `(${q(t)}, ${q(f)})`).join(', ')
  return [
    { label: 'search_tokens rows hashed from encrypted fields', requires: 'search_tokens',
      sql: `select count(*)::bigint as n from "search_tokens" where ("entity_type", "field") in (values ${pairs})` },
    { label: 'search_tokens rows hashed from search_text of encrypted entities', requires: 'search_tokens',
      sql: `select count(*)::bigint as n from "search_tokens" where "entity_type" in (${types}) and "field" = 'search_text'` },
    { label: 'search_tokens rows hashed from encrypted custom fields', requires: 'search_tokens',
      sql: `select count(*)::bigint as n from "search_tokens" st join "custom_field_defs" d on d."entity_id" = st."entity_type" and st."field" in ('cf:' || d."key", 'cf_' || d."key") where (d."config_json"::jsonb ->> 'encrypted') = 'true'` },
    { label: 'search_tokens raw token column set (encrypted entities)', requires: 'search_tokens',
      sql: `select count(*)::bigint as n from "search_tokens" where "token" is not null and "entity_type" in (${types})` },
    { label: 'entity_indexes docs with search_text (encrypted entities)', requires: 'entity_indexes',
      sql: `select count(*)::bigint as n from "entity_indexes" where "entity_type" in (${types}) and "doc" -> 'search_text' is not null` },
    { label: 'vector_search rows of encrypted entities', requires: 'vector_search',
      sql: `select count(*)::bigint as n from "vector_search" where "entity_id" in (${types})` },
  ]
}
