/**
 * Purge plaintext-equivalent copies of encrypted fields the Open Mercato query
 * index and search module wrote before this change:
 * - search_tokens: unkeyed SHA-256 of every word and 3+ char prefix of the
 *   decrypted names, emails, phones, titles, bodies (reversible with a word
 *   list), plus the optional raw `token` column; also tokens of the
 *   search_text aggregate and of encrypted custom fields.
 * - entity_indexes.doc.search_text: an aggregate of every string field,
 *   plaintext for rows indexed while their columns were still plaintext.
 * - vector_search (pgvector, created lazily by the search module): result
 *   title/subtitle/presenter/links in clear for contacts and deals.
 * Plaintext mapped values inside entity_indexes documents need the tenant key
 * to fix, so the backfill script encrypts those (`--phase index-docs`).
 */
export function searchIndexPurgeSql(): string[] {
  const types = encryptedEntityTypes().map(q).join(', ')
  const pairs = encryptedFieldPairs().map(([t, f]) => `(${q(t)}, ${q(f)})`).join(', ')
  // Each purge is skipped when its table does not exist (fresh or partial installs).
  const guarded = (tables: string[], statement: string) =>
    `do $purge$ begin
  if ${tables.map((t) => `to_regclass(${q(t)}) is not null`).join(' and ')} then
    ${statement}
  end if;
end $purge$;`
  return [
    guarded(['search_tokens'], `delete from "search_tokens" where ("entity_type", "field") in (values ${pairs});`),
    guarded(['search_tokens'], `delete from "search_tokens" where "entity_type" in (${types}) and "field" = 'search_text';`),
    guarded(['search_tokens', 'custom_field_defs'], `delete from "search_tokens" st using "custom_field_defs" d
      where d."entity_id" = st."entity_type"
        and st."field" in ('cf:' || d."key", 'cf_' || d."key")
        and (d."config_json"::jsonb ->> 'encrypted') = 'true';`),
    guarded(['search_tokens'], `update "search_tokens" set "token" = null where "token" is not null and "entity_type" in (${types});`),
    guarded(['entity_indexes'], `update "entity_indexes" set "doc" = "doc" - 'search_text' where "entity_type" in (${types}) and "doc" -> 'search_text' is not null;`),
    guarded(['vector_search'], `delete from "vector_search" where "entity_id" in (${types});`),
  ]
}

